const escapedForPattern = (literal: string): string => literal.replaceAll(/[.*+?^${}()|[\]\\]/g, String.raw`\$&`);

const patternOf = (template: string): RegExp => {
  const source = template
    .split(/(<[a-z]+>)/)
    .map((part) => (Object.hasOwn(GENERATED_PARTS, part) ? GENERATED_PARTS[part] : escapedForPattern(part)))
    .join('');
  return new RegExp(`^${source}$`);
};

const TEMPLATE_PATTERNS = TEST_RECORD_NAME_TEMPLATES.map((template) => ({ template, pattern: patternOf(template) }));

/** The template in TEST_RECORD_NAME_TEMPLATES that a record name was made from, if any. */
export function testRecordNameTemplateOf(name: string): string | undefined {
  return TEMPLATE_PATTERNS.find(({ pattern }) => pattern.test(name))?.template;
}
